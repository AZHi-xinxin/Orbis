package me.rerere.rikkahub.data.sync.importer

/** One tested example shared by the screen and copied conversion prompt. */
object UniversalChatGuide {
    val example = """
        {
          "format": "orbis_chat",
          "version": 1,
          "conversations": [
            {
              "id": "my-app/chat-001/main",
              "title": "一段旧对话",
              "messages": [
                {"role": "user", "content": "今天想聊聊星星。", "timestamp": "2026-01-01T20:00:00+08:00"},
                {"role": "assistant", "content": "好呀，你想从哪颗星说起？", "reasoning": "先接住这个话题。", "timestamp": null}
              ]
            }
          ]
        }
    """.trimIndent()

    val instructions = """
        保存为UTF-8编码的.json文件，按以下格式整理。文件可以包含一个或多个会话。

        format固定为字符串"orbis_chat"，version固定为整数1，conversations为会话数组。

        每个会话包含：
        • id：稳定且在文件内唯一的字符串，最多256字。建议“来源/原会话ID/分支ID”。再次转换同一会话时沿用它。
        • title：标题字符串，最多512字。
        • messages：按原始对话顺序排列的消息数组。每个会话至少一条消息，相同角色可以连续出现。

        每条消息包含：
        • role："user"表示人类，"assistant"表示AI。
        • content：正文字符串；换行使用JSON转义，保留原文字和代码。中断的空回复可以保留为空字符串。
        • reasoning：可选，AI思考的字符串；原记录有才填写。人类备注放在content中。
        • timestamp：可选，带时区的ISO 8601字符串，如2026-01-01T20:00:00+08:00；原时间未知时省略或填null。未知时间在Orbis中显示为导入时间，并保留缺失标记。

        只填写以上字段。此格式保存文字和AI思考；附件在正文中保留文件名、原链接或文字说明，文件实体另行保存。历史工具过程可标明来源后作为assistant正文保留，导入后作为历史文字显示。

        多分支请分别整理成完整会话路径，使用不同id和清楚的标题；公共前文会在各窗口保留。messages的数组顺序就是导入顺序，不按时间重排。

        同一助手内，会话id和内容都相同的记录自动跳过；文字、顺序、标题或时间发生变化时另建窗口。选择文件后先核对助手、会话和数量，再确认追加。

        单文件最多1GiB、10000个会话、1000000条消息；单会话最多50000条，解析和保存有64MiB预算；单条序列化消息最多1MiB。超限会提示，长记录可按原顺序分成多个文件或会话；长消息可拆成同一角色的连续消息，完整保留文字。
    """.trimIndent()

    val conversionPrompt = """
        请把我提供的聊天导出文件转换为Orbis通用聊天JSON v1，并生成可下载的UTF-8 .json文件。

        请先检查文件实际结构，再用脚本逐条转换。正文、说话方、消息顺序、原始时间和已有思考按原记录保留；不总结、润色、补写或用省略号代替内容。原文件保持原样。

        先识别普通对话及分支。完整分支分别生成会话，id根据来源、原会话ID和路径稳定生成。时间只有数字时确认秒或毫秒；时间没有时区时询问我，未知时间留null，不猜造。

        只从来源明确标记为AI思考的字段提取reasoning；标签含义不明确时保留在content里。原有工具调用和工具结果如需要保留，作为带“历史工具调用/结果”来源标签的assistant正文，文字原样保存。图片、音频等在content中保留原有文件名/链接/说明，并列出未携带的附件。账号、模型配置、授权、密钥和运行状态属于配置资料，不进入聊天JSON。

        无法确定说话方、消息顺序或如何保留的记录，先报告问题让我决定。转换后校验JSON，核对各会话源消息数、输出消息数、分支与附件数量；拆长消息时列明拆分数。把未纳入内容的类型、数量和原因写进单独的转换报告，不能静默漏掉记录。使用脚本处理长包；若你不能执行脚本，请提供完整可运行脚本及步骤，而不是声称已经生成完整文件。

        如Orbis提示字段位置错误，请对照下面契约修正该位置，保留其他原文。输出文件内容为纯JSON，不含Markdown代码围栏、注释或额外说明。

        【格式约定】
        $instructions

        【可验证的最小示例】
        $example
    """.trimIndent()
}
