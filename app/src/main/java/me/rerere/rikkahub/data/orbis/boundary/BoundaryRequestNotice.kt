package me.rerere.rikkahub.data.orbis.boundary

/** Only recognised local preflight errors are explained. Never render a raw server error or URL. */
fun boundaryRequestFailureNotice(failure: Exception): String = when (failure.message) {
    "暂无可用模型处理申请", "当前 AI 不存在" ->
        "申请未发送：当前没有可用模型，请检查此 AI 的模型和连接设置。（BR01）"
    "正在回复，请等本次回复结束后再修改消息或已读／折叠状态。",
    "旧轮仍在收尾，请稍后整理历史；新消息仍可发送。" ->
        "申请未发送：这段对话的上一轮仍在结束中，请稍后再提交；本次未消耗申请次数。（BR02）"
    "回复恢复记录待核对，暂不修改消息或已读／折叠状态；原记录均保留。",
    "旧轮恢复记录尚未核对，原历史仍保留；新消息仍可发送。",
    "续聊保存尚未核对完成，暂不改写历史；新消息仍可发送。",
    "续聊恢复副本仍在更新，请稍后整理历史。",
    "续聊仍有生成、工具或保存任务，请结束后再整理历史。" ->
        "申请未发送：这段对话还有待完成的保存或恢复记录，本次未消耗申请次数。请保留聊天并反馈此提示。（BR03）"
    "旧轮仍在核对，暂未提交申请。" ->
        "申请未发送：旧请求的状态仍待核对，本次未消耗申请次数。请查看本对话的恢复提示。（BR04）"
    "boundary_not_paused", "boundary_request_unavailable", "继续申请所属 AI 已变化，本次未发送。" ->
        "暂停约定或所属 AI 已变化，请重新打开原对话查看当前状态。（BR05）"
    "本次暂停的3次继续申请已用完，请等待约定时间自动恢复。" ->
        "本次暂停的 3 次继续申请已用完，请等待约定时间自动恢复。"
    else -> "继续申请未完成，请查看本对话中的申请、答复或错误提示；如仍无法提交，请反馈此提示。（BR00）"
}
